-- Portable across PostgreSQL (prod) and H2 in PostgreSQL mode (local/test).

CREATE TABLE short_url (
    code          VARCHAR(32)   PRIMARY KEY,
    destination   VARCHAR(2048) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at    TIMESTAMP WITH TIME ZONE,
    custom_alias  BOOLEAN       NOT NULL,
    active        BOOLEAN       NOT NULL,
    created_by    VARCHAR(128)  NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_short_url_created_by ON short_url (created_by);

-- click_day is stored (UTC) rather than derived so "by day" aggregation is portable and indexable.
CREATE TABLE click_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(32)   NOT NULL REFERENCES short_url (code),
    clicked_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    click_day     DATE          NOT NULL,
    visitor_hash  VARCHAR(16)   NOT NULL,
    user_agent    VARCHAR(256)  NOT NULL,
    referrer      VARCHAR(256)  NOT NULL
);

CREATE INDEX ix_click_event_code_day ON click_event (code, click_day);
CREATE INDEX ix_click_event_clicked_at ON click_event (clicked_at);

-- code is NULL while the original request is still in flight (reservation pattern).
CREATE TABLE idempotency_key (
    scoped_key           VARCHAR(320) PRIMARY KEY,
    payload_fingerprint  VARCHAR(64)  NOT NULL,
    code                 VARCHAR(32),
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_idempotency_key_created_at ON idempotency_key (created_at);

-- Append-only audit trail of orchestrator runs; survives restarts and in-memory run eviction.
CREATE TABLE orchestrator_audit_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id      VARCHAR(32)   NOT NULL,
    stage_id    VARCHAR(64),
    event       VARCHAR(64)   NOT NULL,
    detail      VARCHAR(4000) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_audit_run ON orchestrator_audit_event (run_id, id);
